/**
 * Оценивание неопределённости определения температуры текучести (T), °C
 * по ГОСТ 20287 (Метод А), на основе данных электронной таблицы
 * "МОН-06-2026 Температуры текучести ГОСТ 20287-2023.xlsx".
 *
 * Таблица 1 — Исходные данные:
 *   H5 — Погрешность измерения температуры пробы, °C = 0,1
 *   H6 — Погрешность поддержания температуры бани, °C = 0,5
 *   H7 — Повторяемость, °C = 6
 *
 * Таблица 2 — Результаты измерений:
 *   B11 — Температура текучести, °C - значение Среднее значение tср, °C из Температура текучести,°С по ГОСТ 20287 (Метод А)
 * 
 *
 * Таблица 3 — Бюджет суммарной стандартной неопределённости:
 *   E15 — стандартная неопределённость поправки на погрешность измерения 
 *         температуры пробы, °C
 *   E16 — стандартная неопределённость поправки на погрешность поддержания 
 *         температуры бани, °C
 *   E17 — стандартная неопределённость повторяемости, °C
 *   E18 — стандартная неопределённость отбора проб, °C
 *   E19 — суммарная стандартная неопределённость, °C
 *
 *   F15 — процентный вклад погрешности измерения температуры пробы
 *   F16 — процентный вклад погрешности поддержания температуры бани
 *   F17 — процентный вклад повторяемости
 *   F18 — процентный вклад отбора проб
 *   F19 — сумма вкладов
 *
 *   D19 — расширенная неопределённость (k = 2), °C
 */

// ============================================================
// Таблица 1 — Исходные данные
// ============================================================

/**
 * H5 — Погрешность измерения температуры пробы, °C.
 */
const H5_sampleTempAccuracy = 0.1;

/**
 * H6 — Погрешность поддержания температуры бани, °C.
 */
const H6_bathTempAccuracy = 0.5;

/**
 * H7 — Повторяемость, °C.
 */
const H7_repeatability = 6;

// ============================================================
// Таблица 2 — Результаты измерений
// ============================================================

/**
 * B11 — Температура текучести, °C.
 */
const B11_measuredPourPoint = 0; // Пример: 0 °C

// ============================================================
// Таблица 3 — Бюджет суммарной стандартной неопределённости
// ============================================================

// ------------------------------------------------------------
// Стандартные неопределённости
// ------------------------------------------------------------

/**
 * E15 — стандартная неопределённость поправки на погрешность 
 * измерения температуры пробы, °C.
 * Формула: E15 = H5 / √3
 */
const E15_uSampleTempAccuracy = H5_sampleTempAccuracy / Math.sqrt(3);

/**
 * E16 — стандартная неопределённость поправки на погрешность 
 * поддержания температуры бани, °C.
 * Формула: E16 = H6 / √3
 */
const E16_uBathTempAccuracy = H6_bathTempAccuracy / Math.sqrt(3);

/**
 * E17 — стандартная неопределённость повторяемости, °C.
 * Формула: E17 = H7 / (2,8 * √2)
 */
const E17_uRepeatability = H7_repeatability / (2.8 * Math.sqrt(2));

/**
 * E18 — стандартная неопределённость отбора проб, °C.
 */
const E18_uSampling = 0.353553390593274;

// ------------------------------------------------------------
// Суммарная стандартная неопределённость
// ------------------------------------------------------------

/**
 * E19 — суммарная стандартная неопределённость, °C.
 *
 * Формула из таблицы:
 *   E19 = √( E15² + E16² + E17² + E18² )
 */
const E19_uCombined = Math.sqrt(
  E15_uSampleTempAccuracy ** 2 +
  E16_uBathTempAccuracy ** 2 +
  E17_uRepeatability ** 2 +
  E18_uSampling ** 2
);

// ------------------------------------------------------------
// Процентные вклады
// ------------------------------------------------------------

/**
 * Знаменатель для процентных вкладов.
 * Формула: denom = E15² + E16² + E17² + E18²
 */
const contributionDenominator =
  E15_uSampleTempAccuracy ** 2 +
  E16_uBathTempAccuracy ** 2 +
  E17_uRepeatability ** 2 +
  E18_uSampling ** 2;

/**
 * F15 — процентный вклад погрешности измерения температуры пробы.
 * Формула: F15 = (E15² / (E15²+E16²+E17²+E18²)) · 100
 */
const F15_contributionSampleTemp =
  (E15_uSampleTempAccuracy ** 2 / contributionDenominator) * 100;

/**
 * F16 — процентный вклад погрешности поддержания температуры бани.
 * Формула: F16 = (E16² / (E15²+E16²+E17²+E18²)) · 100
 */
const F16_contributionBathTemp =
  (E16_uBathTempAccuracy ** 2 / contributionDenominator) * 100;

/**
 * F17 — процентный вклад повторяемости.
 * Формула: F17 = (E17² / (E15²+E16²+E17²+E18²)) · 100
 */
const F17_contributionRepeatability =
  (E17_uRepeatability ** 2 / contributionDenominator) * 100;

/**
 * F18 — процентный вклад отбора проб.
 * Формула: F18 = (E18² / (E15²+E16²+E17²+E18²)) · 100
 */
const F18_contributionSampling =
  (E18_uSampling ** 2 / contributionDenominator) * 100;

/**
 * F19 — сумма процентных вкладов.
 * Формула: F19 = СУММ(F15:F18)
 */
const F19_contributionTotal =
  F15_contributionSampleTemp +
  F16_contributionBathTemp +
  F17_contributionRepeatability +
  F18_contributionSampling;

// ------------------------------------------------------------
// Расширенная неопределённость
// ------------------------------------------------------------

/**
 * D19 — расширенная неопределённость при k = 2, °C.
 */
const D19_expandedUncertainty =
  Math.round(Math.sqrt(contributionDenominator) * 2);

