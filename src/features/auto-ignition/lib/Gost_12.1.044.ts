/**
 * Оценивание неопределённости определения температуры самовоспламенения (T), °C
 * по ГОСТ 12.1.044 п. 31, на основе данных электронной таблицы
 * (МОН-06-2026 Температуры текучести ГОСТ 20287-2023.xlsx).
 *
 * Таблица 1 — Исходные данные:
 *   H5 — Погрешность поддержания температуры бани, °C = 2
 *   H6 — Повторяемость, °C
 *        Формула: =ОКРУГЛ(0,02*B10;0)
 *
 * Таблица 2 — Результаты измерений:
 *   B10 — Температура самовоспламенения, °C
 *         (=Масло!I108)
 *
 * Таблица 3 — Бюджет суммарной стандартной неопределённости:
 *   E14 — стандартная неопределённость поправки на погрешность поддержания 
 *         температуры бани, °C
 *   E15 — стандартная неопределённость повторяемости, °C
 *   E16 — стандартная неопределённость отбора проб, °C
 *   E17 — суммарная стандартная неопределённость, °C
 *
 *   F14 — процентный вклад погрешности поддержания температуры бани
 *   F15 — процентный вклад повторяемости
 *   F16 — процентный вклад отбора проб
 *   F17 — сумма вкладов
 *
 *   D17 — расширенная неопределённость (k = 2), °C
 */

// ============================================================
// Таблица 2 — Результаты измерений (перенесено вверх для расчета H6)
// ============================================================

/**
 * B10 — Температура самовоспламенения, °C. - значение из Среднее значение tср, °C из Температура самовоспламенения, °С по ГОСТ 12.1.044 п. 31
 */
const B10_measuredFlashPoint = 250; // Пример: 250 °C

// ============================================================
// Таблица 1 — Исходные данные
// ============================================================

/**
 * H5 — Погрешность поддержания температуры бани, °C.
 */
const H5_bathTempAccuracy = 2;

/**
 * H6 — Повторяемость, °C.
 * Формула из таблицы: =ОКРУГЛ(0,02*B10;0)
 */
const H6_repeatability = Math.round(0.02 * B10_measuredFlashPoint);

// ============================================================
// Таблица 3 — Бюджет суммарной стандартной неопределённости
// ============================================================

// ------------------------------------------------------------
// Стандартные неопределённости
// ------------------------------------------------------------

/**
 * E14 — стандартная неопределённость поправки на погрешность 
 * поддержания температуры бани, °C.
 * Формула: E14 = H5 / √3
 */
const E14_uBathTempAccuracy = H5_bathTempAccuracy / Math.sqrt(3);

/**
 * E15 — стандартная неопределённость повторяемости, °C.
 * Формула: E15 = H6 / (2,8 * √2)
 */
const E15_uRepeatability = H6_repeatability / (2.8 * Math.sqrt(2));

/**
 * E16 — стандартная неопределённость отбора проб, °C.
 * Задана числом в электронной таблице.
 */
const E16_uSampling = 3.31191032487294;

// ------------------------------------------------------------
// Суммарная стандартная неопределённость
// ------------------------------------------------------------

/**
 * E17 — суммарная стандартная неопределённость, °C.
 *
 * Формула из таблицы:
 *   E17 = √( E14² + E15² + E16² )
 */
const E17_uCombined = Math.sqrt(
  E14_uBathTempAccuracy ** 2 +
  E15_uRepeatability ** 2 +
  E16_uSampling ** 2
);

// ------------------------------------------------------------
// Процентные вклады
// ------------------------------------------------------------

/**
 * Знаменатель для процентных вкладов.
 * Формула: denom = E14² + E15² + E16²
 */
const contributionDenominator =
  E14_uBathTempAccuracy ** 2 +
  E15_uRepeatability ** 2 +
  E16_uSampling ** 2;

/**
 * F14 — процентный вклад погрешности поддержания температуры бани.
 * Формула: F14 = (E14² / (E14²+E15²+E16²)) · 100
 */
const F14_contributionBathTemp =
  (E14_uBathTempAccuracy ** 2 / contributionDenominator) * 100;

/**
 * F15 — процентный вклад повторяемости.
 * Формула: F15 = (E15² / (E14²+E15²+E16²)) · 100
 */
const F15_contributionRepeatability =
  (E15_uRepeatability ** 2 / contributionDenominator) * 100;

/**
 * F16 — процентный вклад отбора проб.
 * Формула: F16 = (E16² / (E14²+E15²+E16²)) · 100
 */
const F16_contributionSampling =
  (E16_uSampling ** 2 / contributionDenominator) * 100;

/**
 * F17 — сумма процентных вкладов.
 * Формула: F17 = СУММ(F14:F16)
 */
const F17_contributionTotal =
  F14_contributionBathTemp +
  F15_contributionRepeatability +
  F16_contributionSampling;

// ------------------------------------------------------------
// Расширенная неопределённость
// ------------------------------------------------------------

/**
 * D17 — расширенная неопределённость при k = 2, °C.
 *
 * Формула: =2*√( E14² + E15² + E16² ) - округление до целого числа
 */
const D17_expandedUncertainty =
  Math.round(Math.sqrt(contributionDenominator) * 2);

// ============================================================
// Экспорт
// ============================================================

export {
  B10_measuredFlashPoint,
  H5_bathTempAccuracy,
  H6_repeatability,
  E14_uBathTempAccuracy,
  E15_uRepeatability,
  E16_uSampling,
  E17_uCombined,
  F14_contributionBathTemp,
  F15_contributionRepeatability,
  F16_contributionSampling,
  F17_contributionTotal,
  D17_expandedUncertainty,
};