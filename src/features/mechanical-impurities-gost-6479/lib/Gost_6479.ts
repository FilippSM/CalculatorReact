/**
 * Оценивание неопределённости определения массовой доли механических примесей (X)
 * (на основе данных электронной таблицы).
 *
 * Таблица 1 — Средства измерений и исходные данные:
 *   G5 — Весы лабораторные электронные PS 6000/C2/N, погрешность, г = 0.01
 *   G6 — Весы лабораторные электронные AS 220/C2, погрешность, г = 0.0001
 *   G7 — Расхождение между двумя последовательными взвешиваниями, г = 0.0004
 *   G8 — Предел повторяемости, % = 0.025
 *
 * Таблица 2 — Результаты измерений:
 *   A13 — Масса испытуемого нефтепродукта, г - значение Масса пробы m₃, г для первого измерения из Содержание механических примесей, % по ГОСТ 6479
 *   B13 — Масса стаканчика с фильтром с примесями, г - Масса стакана + фильтр + мех. примеси m₁, г для первого измерения из Содержание механических примесей, % по ГОСТ 6479
 *   C13 — Масса стаканчика с чистым фильтром, г - Масса стакана + фильтр m₂, г	Масса для первого измерения из Содержание механических примесей, % по ГОСТ 6479
 *   D12 — Среднее значение массовой доли (по ГОСТ 6479), %
 *   F13 — Коэффициент чувствительности (C1)
 *   G13 — Коэффициент чувствительности (C2)
 *   H13 — Коэффициент чувствительности (C3)
 *
 * Таблица 3 — Бюджет суммарной стандартной неопределённости:
 *   D21 — стандартная неопределённость массы испытуемого нефтепродукта, г
 *   D22 — стандартная неопределённость массы стаканчика с фильтром с примесями, г
 *   D23 — стандартная неопределённость массы стаканчика с чистым фильтром, г
 *   D24 — стандартная неопределённость повторяемости метода, %
 *   D25 — стандартная неопределённость отбора проб, % (в таблице не задана, принимаем 0)
 *   D26 — суммарная стандартная неопределённость, %
 *
 *   E21 — процентный вклад массы испытуемого нефтепродукта
 *   E22 — процентный вклад массы стаканчика с фильтром с примесями
 *   E23 — процентный вклад массы стаканчика с чистым фильтром
 *   E24 — процентный вклад повторяемости метода
 *   E25 — процентный вклад отбора проб
 *   E26 — сумма вкладов
 *
 *   (без номера) — расширенная неопределённость (k = 2), %
 */

// ============================================================
// Таблица 1 — Средства измерений и исходные данные
// ============================================================

/**
 * G5 — Погрешность весов, г -  PS 6000/C2/N.
 */
const G5_balanceAccuracy = 0.01;

/**
 * G6 — Погрешность весов, г - AS 220/C2.
 */
const G6_balanceAccuracy = 0.0001;

/**
 * G7 — Расхождение между двумя последовательными взвешиваниями, г
 */
const G7_repeatability = 0.0004;

/**
 * G8 — Предел повторяемости метода, %.
 */
const G8_repeatability = 0.025;

// ============================================================
// Таблица 2 — Результаты измерений
// ============================================================

/**
 * Исходные данные для коэффициентов чувствительности
 */

/**
 * A13 — Масса испытуемого нефтепродукта (Масса пробы m₃), г
 */
const A13_sampleMass = 100.0;

/**
 * B13 — Масса стаканчика с фильтром с примесями (Масса стакана + фильтр + мех. примеси m₁), г
 */
const B13_filterWithImpuritiesMass = 50.0;

/**
 * C13 — Масса стаканчика с чистым фильтром (Масса стакана + фильтр m₂), г
 */
const C13_cleanFilterMass = 49.9;

/**
 * D12 — Итоговое среднее значение массовой доли механических примесей, %. - значение из Среднее значение X, % из Содержание механических примесей, % по ГОСТ 6479
 */
const D12_meanMassFraction = 0.025; 

/**
 * Определение количества знаков после запятой у D12 для последующего округления неопределенности.
 * (Например, для 0.025 количество знаков = 3)
 */
function getDecimalPlaces(num: number): number {
  const str = num.toString();
  if (str.includes('.')) {
    return str.split('.')[1].length;
  }
  return 0;
}

const decimalPlaces = getDecimalPlaces(D12_meanMassFraction);

// ============================================================
// Коэффициенты чувствительности
// ============================================================

/**
 * F13 — Коэффициент чувствительности (C1)
 * Формула: C1 = (B13 - C13) * 100 / (A13^2)
 */
const F13_sensitivityFactor = (B13_filterWithImpuritiesMass - C13_cleanFilterMass) * 100 / (A13_sampleMass ** 2);

/**
 * G13 — Коэффициент чувствительности (C2)
 * Формула: C2 = 100 / A13
 */
const G13_sensitivityFactor = 100 / A13_sampleMass;

/**
 * H13 — Коэффициент чувствительности (C3)
 * Формула: C3 = -100 / A13
 */
const H13_sensitivityFactor = -100 / A13_sampleMass;

// ============================================================
// Таблица 3 — Бюджет суммарной стандартной неопределённости
// ============================================================

// ------------------------------------------------------------
// Стандартные неопределённости
// ------------------------------------------------------------

/**
 * D21 — стандартная неопределённость массы испытуемого нефтепродукта, г
 */
const D21_uSampleMass = G5_balanceAccuracy / Math.sqrt(3);

/**
 * D22 — стандартная неопределённость массы стаканчика с фильтром с примесями, г
 */
const D22_uFilterWithImpuritiesMass = Math.sqrt(
  (G6_balanceAccuracy / Math.sqrt(3)) ** 2 + (G7_repeatability / 2.8) ** 2
);

/**
 * D23 — стандартная неопределённость массы стаканчика с чистым фильтром, г
 */
const D23_uCleanFilterMass = Math.sqrt(
  (G6_balanceAccuracy / Math.sqrt(3)) ** 2 + (G7_repeatability / 2.8) ** 2
);

/**
 * D24 — стандартная неопределённость повторяемости метода, %
 */
const D24_uRepeatability = G8_repeatability / 2.8;

/**
 * D25 — стандартная неопределённость отбора проб, %
 */
const D25_uSampling = 0;

// ------------------------------------------------------------
// Суммарная стандартная неопределённость
// ------------------------------------------------------------

const varianceSum =
  D21_uSampleMass ** 2 * F13_sensitivityFactor ** 2 +
  D22_uFilterWithImpuritiesMass ** 2 * G13_sensitivityFactor ** 2 +
  D23_uCleanFilterMass ** 2 * H13_sensitivityFactor ** 2 +
  D24_uRepeatability ** 2 +
  D25_uSampling ** 2;

/**
 * D26 — суммарная стандартная неопределённость, %.
 */
const D26_uCombined = Math.sqrt(varianceSum);

// ------------------------------------------------------------
// Процентные вклады
// ------------------------------------------------------------

/**
 * E21 — процентный вклад массы испытуемого нефтепродукта.
 */
const E21_contributionSampleMass =
  (D21_uSampleMass ** 2 * F13_sensitivityFactor ** 2 / varianceSum) * 100;

/**
 * E22 — процентный вклад массы стаканчика с фильтром с примесями.
 */
const E22_contributionFilterWithImpurities =
  (D22_uFilterWithImpuritiesMass ** 2 * G13_sensitivityFactor ** 2 / varianceSum) * 100;

/**
 * E23 — процентный вклад массы стаканчика с чистым фильтром.
 */
const E23_contributionCleanFilter =
  (D23_uCleanFilterMass ** 2 * H13_sensitivityFactor ** 2 / varianceSum) * 100;

/**
 * E24 — процентный вклад повторяемости метода.
 */
const E24_contributionRepeatability =
  (D24_uRepeatability ** 2 / varianceSum) * 100;

/**
 * E25 — процентный вклад отбора проб.
 */
const E25_contributionSampling =
  (D25_uSampling ** 2 / varianceSum) * 100;

const E26_contributionTotal =
  E21_contributionSampleMass +
  E22_contributionFilterWithImpurities +
  E23_contributionCleanFilter +
  E24_contributionRepeatability +
  E25_contributionSampling;

// ------------------------------------------------------------
// Расширенная неопределённость
// ------------------------------------------------------------

/**
 * Расширенная неопределённость при k = 2, %.
 * Округляется до стольки знаков после запятой, сколько их у D12 (среднего значения).
 */
const expandedUncertaintyRaw = 2 * D26_uCombined;

// Математическое округление до нужного количества знаков после запятой
const expandedUncertainty = Number(expandedUncertaintyRaw.toFixed(decimalPlaces));

// ============================================================
// Экспорт
// ============================================================

export {
  G5_balanceAccuracy,
  G6_balanceAccuracy,
  G7_repeatability,
  G8_repeatability,
  A13_sampleMass,
  B13_filterWithImpuritiesMass,
  C13_cleanFilterMass,
  D12_meanMassFraction,
  F13_sensitivityFactor,
  G13_sensitivityFactor,
  H13_sensitivityFactor,
  D21_uSampleMass,
  D22_uFilterWithImpuritiesMass,
  D23_uCleanFilterMass,
  D24_uRepeatability,
  D25_uSampling,
  D26_uCombined,
  E21_contributionSampleMass,
  E22_contributionFilterWithImpurities,
  E23_contributionCleanFilter,
  E24_contributionRepeatability,
  E25_contributionSampling,
  E26_contributionTotal,
  expandedUncertainty,
};